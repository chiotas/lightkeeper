#!/usr/bin/env python3
"""Writes the clock's typefaces into app/clock/: only the characters a clock needs.
Then measures where each digit's ink starts and ends, which logos.js uses to line the clock up.

    python3 docs/art/clock-fonts.py <folder with the source fonts>
    python3 docs/art/clock-fonts.py --measure     the measures only, from app/

Needs fontTools and brotli. The sources, all under the SIL Open Font License 1.1, whose texts
are copied beside the fonts as app/clock/OFL-<name>.txt:

    cormorant.ttf      CormorantGaramond[wght].ttf, github.com/google/fonts ofl/cormorantgaramond
    jetbrainsmono.ttf  JetBrainsMono[wght].ttf, github.com/google/fonts ofl/jetbrainsmono
    nunito.ttf         Nunito[wght].ttf, github.com/google/fonts ofl/nunito
    DSEG7Classic-Light.ttf  fonts-DSEG_v046.zip, github.com/keshikan/DSEG releases v0.46

DSEG has the Reserved Font Name "DSEG": a subset is a modified version, so it is renamed.
"""
import json, os, re, sys
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen
from fontTools.varLib import instancer
from fontTools import subset

TEXT = '0123456789:AMP '
SRC = sys.argv[1]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'app', 'clock')
FONTS = [  # name in Lightkeeper, source file, weight to fix a variable font at, new family name or None
    ('classic', 'cormorant.ttf', 300, None),
    ('mono', 'jetbrainsmono.ttf', 200, None),
    ('rounded', 'nunito.ttf', 300, None),
    ('digital', 'DSEG7Classic-Light.ttf', None, 'Lightkeeper Segments'),
]
APP = os.path.join(OUT, '..')

def substitutions(font, features):
    swap = {}
    if features and 'GSUB' in font:
        table = font['GSUB'].table
        for rec in table.FeatureList.FeatureRecord:
            if rec.FeatureTag in features:
                for i in rec.Feature.LookupListIndex:
                    for st in table.LookupList.Lookup[i].SubTable:
                        swap.update(getattr(st, 'mapping', {}) or {})
    return swap

def ink_ends(path, chars, features=()):
    """How far before its advance each character's ink ends, in em: its right side bearing."""
    font = TTFont(path)
    gs, cmap, upm = font.getGlyphSet(), font.getBestCmap(), font['head'].unitsPerEm
    swap = substitutions(font, features)
    out = []
    for ch in chars:
        g = swap.get(cmap[ord(ch)], cmap[ord(ch)])
        pen = BoundsPen(gs)
        gs[g].draw(pen)
        out.append(round((gs[g].width - pen.bounds[2]) / upm, 3) if pen.bounds else 0)
    return out

def ink_starts(path, features=()):
    """Where each digit's ink starts, in em, with the given GSUB single substitutions applied."""
    font = TTFont(path)
    gs, cmap, upm = font.getGlyphSet(), font.getBestCmap(), font['head'].unitsPerEm
    swap = {}
    if features and 'GSUB' in font:
        table = font['GSUB'].table
        for rec in table.FeatureList.FeatureRecord:
            if rec.FeatureTag in features:
                for i in rec.Feature.LookupListIndex:
                    for st in table.LookupList.Lookup[i].SubTable:
                        swap.update(getattr(st, 'mapping', {}) or {})
    out = []
    for d in '0123456789':
        g = cmap[ord(d)]
        g = swap.get(g, g)
        pen = BoundsPen(gs)
        gs[g].draw(pen)
        out.append(round(pen.bounds[0] / upm, 3) if pen.bounds else 0)
    return out

def measure():
    # Thin, Jost 200, is left as it has always been drawn.
    table = {
        'bold': ink_starts(os.path.join(APP, 'jost-500.woff2')),
        'classic': ink_starts(os.path.join(OUT, 'classic.woff2'), ('lnum',)),
        'mono': ink_starts(os.path.join(OUT, 'mono.woff2')),
        'rounded': ink_starts(os.path.join(OUT, 'rounded.woff2')),
        'digital': ink_starts(os.path.join(OUT, 'digital.woff2')),
    }
    block = ('// RIENTRO:BEGIN generated by docs/art/clock-fonts.py: where each digit\'s ink starts, in em\n'
             'var RIENTRO_ORA = %s;\n// RIENTRO:END') % json.dumps(table, sort_keys=True)
    target = os.path.join(APP, 'logos.js')
    src = open(target).read()
    src = re.sub(r'// RIENTRO:BEGIN.*?// RIENTRO:END', lambda m: block, src, flags=re.S)
    open(target, 'w').write(src)
    for k in sorted(table): print('%-8s %s' % (k, table[k]))
    # The right side: each digit's ink end, then that of the "M" of AM and PM in the clock's
    # small type (Jost 300 for Thin, Bold and Digital), and of the weather line's "°".
    jost300 = os.path.join(APP, 'jost-300.woff2')
    ends = {
        'thin': ink_ends(os.path.join(APP, 'jost-200.woff2'), '0123456789') + ink_ends(jost300, 'M'),
        'bold': ink_ends(os.path.join(APP, 'jost-500.woff2'), '0123456789') + ink_ends(jost300, 'M'),
        'classic': ink_ends(os.path.join(OUT, 'classic.woff2'), '0123456789', ('lnum',)) + ink_ends(os.path.join(OUT, 'classic.woff2'), 'M'),
        'mono': ink_ends(os.path.join(OUT, 'mono.woff2'), '0123456789M'),
        'rounded': ink_ends(os.path.join(OUT, 'rounded.woff2'), '0123456789M'),
        'digital': ink_ends(os.path.join(OUT, 'digital.woff2'), '0123456789') + ink_ends(jost300, 'M'),
        'deg': ink_ends(jost300, '\u00b0')[0],
    }
    block = ('// RIENTRO_DX:BEGIN generated by docs/art/clock-fonts.py: where each digit\'s ink ends, then\n'
             '// the "M" of AM/PM in the clock\'s small type, before the advance, in em; "deg": the weather\'s "\u00b0"\n'
             'var RIENTRO_DX = %s;\n// RIENTRO_DX:END') % json.dumps(ends, sort_keys=True)
    src = open(target).read()
    if '// RIENTRO_DX:BEGIN' in src:
        src = re.sub(r'// RIENTRO_DX:BEGIN.*?// RIENTRO_DX:END', lambda m: block, src, flags=re.S)
    else:
        src = src.replace('// RIENTRO:END', '// RIENTRO:END\n' + block)
    open(target, 'w').write(src)
    for k in sorted(ends): print('%-8s %s' % (k, ends[k]))

if SRC == '--measure':
    measure()
    sys.exit(0)
os.makedirs(OUT, exist_ok=True)
for name, src, weight, rename in FONTS:
    font = TTFont(os.path.join(SRC, src))
    if weight is not None and 'fvar' in font:
        font = instancer.instantiateVariableFont(font, {'wght': weight})
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.hinting = False
    opts.name_IDs = ['*']
    opts.layout_features = opts.layout_features + ['lnum']  # Cormorant's lining figures, which the page turns on
    sub = subset.Subsetter(opts)
    sub.populate(text=TEXT)
    sub.subset(font)
    if rename:
        for rec in font['name'].names:
            if rec.nameID in (1, 3, 4, 6, 16, 17, 21, 22):
                rec.string = rename.replace(' ', '') if rec.nameID == 6 else rename
    path = os.path.join(OUT, name + '.woff2')
    font.flavor = 'woff2'
    font.save(path)
    print('%-8s %5d bytes  %s' % (name, os.path.getsize(path), ''.join(sorted(set(TEXT) & set(chr(c) for c in font.getBestCmap())))))
measure()
