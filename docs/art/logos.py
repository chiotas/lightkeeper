#!/usr/bin/env python3
"""Writes the logo shapes into app/logos.js, from an unpacked Simple Icons package.

    npm pack simple-icons@16.35.0 && tar -xzf simple-icons-16.35.0.tgz
    python3 docs/art/logos.py package

Only the path data and each icon's title are taken: the drawings are CC0, the trademarks stay their owners'.
The titles name the logos in the settings' icon grid.
"""
import json, os, re, sys, unicodedata

SLUGS = ['netflix', 'youtube', 'plex', 'spotify', 'twitch', 'appletv', 'dazn', 'crunchyroll', 'paramountplus',
         'mubi', 'tidal', 'applemusic', 'jellyfin', 'kodi', 'emby', 'vimeo',
         'playstation5', 'playstation4', 'steamdeck', 'nvidia', 'googletv', 'roku', 'accuweather', 'lg',
         # More streaming services (October 2026): the brand's mark where the app has none of its own,
         # such as RTL for RTL+, Movistar for Movistar Plus+, Red Bull for Red Bull TV.
         'tubi', 'youtubetv', 'fubo', 'nbc', 'starz', 'cnn', 'nba', 'mlb', 'nhl', 'ufc', 'ted', 'dailymotion',
         'deezer', 'soundcloud', 'pandora', 'iheartradio', 'itvx', 'channel4', 'zdf', 'rtl', 'movistar', 'viaplay', 'redbull']
pkg = sys.argv[1]
version = json.load(open(os.path.join(pkg, 'package.json')))['version']
def slug(title):
    # As Simple Icons makes a slug from a title, for the icons whose data gives none.
    for a, b in (('+', 'plus'), ('.', 'dot'), ('&', 'and')): title = title.replace(a, b)
    title = unicodedata.normalize('NFD', title.lower())
    return re.sub(r'[^a-z0-9]', '', title)
data = json.load(open(os.path.join(pkg, 'data', 'simple-icons.json')))
titles = dict((i.get('slug') or slug(i['title']), i['title']) for i in data)
shapes = {}
for s in SLUGS:
    svg = open(os.path.join(pkg, 'icons', s + '.svg')).read()
    paths = re.findall(r' d="([^"]+)"', svg)
    assert len(paths) == 1, s
    shapes[s] = paths[0]
block = '// LOGHI:BEGIN generated by docs/art/logos.py from Simple Icons %s\nvar SIMPLE_ICONS = %s;\nvar SIMPLE_ICONS_NOMI = %s;\n// LOGHI:END' % (
    version, json.dumps(shapes, indent=0, sort_keys=True),
    json.dumps(dict((s, titles[s]) for s in SLUGS), sort_keys=True, ensure_ascii=False))
target = os.path.join(os.path.dirname(__file__), '..', '..', 'app', 'logos.js')
src = open(target).read()
src = re.sub(r'// LOGHI:BEGIN.*?// LOGHI:END', lambda m: block, src, flags=re.S)
open(target, 'w').write(src)
print('%d logos from Simple Icons %s' % (len(shapes), version))
